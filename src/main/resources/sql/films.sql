CREATE TABLE IF NOT EXISTS films.mpa
(
    id   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(20) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS films.films
(
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(30) NOT NULL,
    description  varchar(200),
    release_date date,
    duration     smallint CHECK (duration > 0),
    mpa          integer REFERENCES films.mpa(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS films.genre
(
    id   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(20) NOT NULL UNIQUE
);


CREATE TABLE IF NOT EXISTS films.film_genres
(
    film_id  bigint REFERENCES films.films(id) ON DELETE CASCADE ,
    genre_id smallint REFERENCES films.genre(id) ON DELETE CASCADE ,
    PRIMARY KEY (film_id, genre_id)
);

CREATE TABLE IF NOT EXISTS films.popular
(
    film_id bigint NOT NULL REFERENCES films.films(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users.users(id) ON DELETE CASCADE,
    PRIMARY KEY (film_id, user_id)
);